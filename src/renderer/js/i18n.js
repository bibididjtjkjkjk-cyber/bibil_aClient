export const LOCALES = [
  { value: 'ru', label: 'Русский' },
  { value: 'uk', label: 'Українська' },
  { value: 'en', label: 'English' },
];

let current = 'ru';

export function setLocale(value) {
  current = DICT[value] ? value : 'ru';
  document.documentElement.dataset.lang = current;
  document.documentElement.lang = current === 'uk' ? 'uk' : current === 'en' ? 'en' : 'ru';
}

export function getLocale() {
  return current;
}

export function localeLabel() {
  return LOCALES.find((l) => l.value === current)?.label || 'Русский';
}

/** Перекладає рядок і підставляє {підмінні} значення. */
export function t(text, vars) {
  let out = DICT[current]?.[text] ?? text;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(v ?? ''));
  }
  return out;
}

/** Локаль для дат і часу. */
export function dateLocale() {
  return current === 'uk' ? 'uk-UA' : current === 'en' ? 'en-US' : 'ru-RU';
}
